import hashlib
import base64
import secrets
from cryptography.hazmat.primitives.ciphers.aead import AESGCM


# ==========================================
# 1. DIFFIE-HELLMAN FUNCTIONS
# ==========================================

def is_prime(n):
    if n < 2:
        return False

    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            return False

    return True


def prime_factors(n):
    factors = set()
    d = 2

    while d * d <= n:
        if n % d == 0:
            factors.add(d)

            while n % d == 0:
                n //= d

        d += 1

    if n > 1:
        factors.add(n)

    return factors


def is_primitive_root(alpha, q):
    if not is_prime(q):
        return False

    if not (1 < alpha < q):
        return False

    phi = q - 1

    for factor in prime_factors(phi):
        if pow(alpha, phi // factor, q) == 1:
            return False

    return True


def calculate_public_key(alpha, private_key, q):
    return pow(alpha, private_key, q)


def calculate_shared_key(received_key, private_key, q):
    return pow(received_key, private_key, q)


# ==========================================
# 2. AES KEY DERIVATION
# ==========================================

def derive_aes_key(shared_key):
    return hashlib.sha256(
        str(shared_key).encode("utf-8")
    ).digest()


# ==========================================
# 3. ENCRYPTION
# ==========================================

def encrypt_message(message, aes_key):

    aesgcm = AESGCM(aes_key)

    # Generate a random 12-byte nonce
    nonce = secrets.token_bytes(12)

    # Encrypt the message
    ciphertext = aesgcm.encrypt(
        nonce,
        message.encode("utf-8"),
        None
    )

    # Combine nonce and ciphertext
    encrypted_data = nonce + ciphertext

    # Encode using Base64
    return base64.b64encode(encrypted_data).decode("utf-8")


# ==========================================
# 4. DECRYPTION
# ==========================================

def decrypt_message(encrypted_message, aes_key):

    encrypted_data = base64.b64decode(encrypted_message)

    # Extract nonce and ciphertext
    nonce = encrypted_data[:12]
    ciphertext = encrypted_data[12:]

    aesgcm = AESGCM(aes_key)

    # Decrypt the message
    plaintext = aesgcm.decrypt(
        nonce,
        ciphertext,
        None
    )

    return plaintext.decode("utf-8")


