# 5. MAIN PROGRAM
# ==========================================

def main():

    print("======================================")
    print(" DIFFIE-HELLMAN & AES-GCM APPLICATION")
    print("======================================")

    try:
        # Input public parameters
        q = int(input("Enter prime number q: "))
        alpha = int(input("Enter primitive root alpha: "))

        # Validate public parameters
        if not is_prime(q):
            print("Error: q must be a prime number.")
            return

        if not is_primitive_root(alpha, q):
            print("Error: alpha must be a primitive root modulo q.")
            return

        # Input private keys
        xA = int(input("Enter Alice's private key: "))
        xB = int(input("Enter Bob's private key: "))

        # Validate private keys
        if not (1 <= xA < q - 1):
            print("Error: Alice's private key is invalid.")
            return

        if not (1 <= xB < q - 1):
            print("Error: Bob's private key is invalid.")
            return

        # Generate public keys
        yA = calculate_public_key(alpha, xA, q)
        yB = calculate_public_key(alpha, xB, q)

        print("\n========== PUBLIC KEY GENERATION ==========")
        print("Alice's public key:", yA)
        print("Bob's public key:", yB)

        # Simulate public key exchange
        print("\n========== PUBLIC KEY EXCHANGE ==========")
        print("Alice receives Bob's public key:", yB)
        print("Bob receives Alice's public key:", yA)

        # Calculate shared keys
        KA = calculate_shared_key(yB, xA, q)
        KB = calculate_shared_key(yA, xB, q)

        print("\n========== SHARED KEY GENERATION ==========")
        print("Alice's shared key:", KA)
        print("Bob's shared key:", KB)

        # Verify shared keys
        if KA != KB:
            print("Key exchange failed!")
            return

        print("\nKey exchange successful!")

        # Derive AES keys
        aes_key_A = derive_aes_key(KA)
        aes_key_B = derive_aes_key(KB)

        # ==================================
        # ENCRYPTION
        # ==================================

        print("\n========== MESSAGE ENCRYPTION ==========")

        message = input("Enter your message: ")

        encrypted_message = encrypt_message(
            message,
            aes_key_A
        )

        print("\nOriginal message:")
        print(message)

        print("\nEncrypted message:")
        print(encrypted_message)

        # ==================================
        # DECRYPTION
        # ==================================

        print("\n========== MESSAGE DECRYPTION ==========")

        decrypted_message = decrypt_message(
            encrypted_message,
            aes_key_B
        )

        print("\nDecrypted message:")
        print(decrypted_message)

        # Verify decrypted message
        if decrypted_message == message:
            print("\nDecryption successful!")
            print("Original and decrypted messages match.")
        else:
            print("\nDecryption failed!")

    except ValueError:
        print("Error: Please enter valid integer values.")

    except Exception as e:
        print("An error occurred:", str(e))


# ==========================================
# 6. RUN PROGRAM
# ==========================================

if __name__ == "__main__":
    main()