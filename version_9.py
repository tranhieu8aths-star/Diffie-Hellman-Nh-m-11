# VERSION 9: PUBLIC PARAMETER VALIDATION

def is_prime(n):
    if n < 2:
        return False

    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            return False

    return True


def prime_factors(n):
    factors = set()
    d = 2

    while d * d <= n:
        if n % d == 0:
            factors.add(d)
            while n % d == 0:
                n //= d
        d += 1

    if n > 1:
        factors.add(n)

    return factors


def is_primitive_root(alpha, q):
    if not (1 < alpha < q):
        return False

    for r in prime_factors(q - 1):
        if pow(alpha, (q - 1) // r, q) == 1:
            return False

    return True


def calculate_public_key(alpha, private_key, q):
    return pow(alpha, private_key, q)


def calculate_shared_key(received_key, private_key, q):
    return pow(received_key, private_key, q)


try:
    q = int(input("Enter prime number q: "))
    alpha = int(input("Enter primitive root alpha: "))

    if not is_prime(q):
        print("Error: q must be a prime number!")

    elif not is_primitive_root(alpha, q):
        print("Error: alpha is not a primitive root!")

    else:
        xA = int(input("Enter private key of A: "))
        xB = int(input("Enter private key of B: "))

        if not (1 <= xA < q - 1 and 1 <= xB < q - 1):
            print("Error: Invalid private key!")

        else:
            yA = calculate_public_key(alpha, xA, q)
            yB = calculate_public_key(alpha, xB, q)

            KA = calculate_shared_key(yB, xA, q)
            KB = calculate_shared_key(yA, xB, q)

            print("\nPublic key A:", yA)
            print("Public key B:", yB)
            print("Shared key A:", KA)
            print("Shared key B:", KB)

            if KA == KB:
                print("SUCCESS: Both parties have the same key!")

except ValueError:
    print("Error: Please enter valid integers!")