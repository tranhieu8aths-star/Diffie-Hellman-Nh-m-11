# VERSION 5: PUBLIC KEY GENERATION

def calculate_public_key(alpha, private_key, q):
    return pow(alpha, private_key, q)


q = 353
alpha = 3

try:
    xA = int(input("Enter private key of A: "))
    xB = int(input("Enter private key of B: "))

    if not (1 <= xA < q - 1 and 1 <= xB < q - 1):
        print("Error: Invalid private key!")

    else:
        yA = calculate_public_key(alpha, xA, q)
        yB = calculate_public_key(alpha, xB, q)

        print("Public key A:", yA)
        print("Public key B:", yB)

except ValueError:
    print("Error: Please enter integers only!")