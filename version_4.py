# VERSION 4: PRIVATE KEY VALIDATION

q = 353
alpha = 3

try:
    xA = int(input("Enter private key of A: "))
    xB = int(input("Enter private key of B: "))

    if not (1 <= xA < q - 1):
        print("Error: Invalid private key A!")

    elif not (1 <= xB < q - 1):
        print("Error: Invalid private key B!")

    else:
        yA = pow(alpha, xA, q)
        yB = pow(alpha, xB, q)

        KA = pow(yB, xA, q)
        KB = pow(yA, xB, q)

        print("\nPublic key A:", yA)
        print("Public key B:", yB)
        print("Shared key A:", KA)
        print("Shared key B:", KB)

except ValueError:
    print("Error: Please enter integers only!")