# 1. CHECK WHETHER A NUMBER IS PRIME
def is_prime(n):
    if n < 2:
        return False

    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            return False

    return True


# 2. FIND DISTINCT PRIME FACTORS OF q - 1
def prime_factors(n):
    factors = set()
    divisor = 2

    while divisor * divisor <= n:
        if n % divisor == 0:
            factors.add(divisor)

            while n % divisor == 0:
                n //= divisor

        divisor += 1

    if n > 1:
        factors.add(n)

    return factors


# 3. CHECK WHETHER alpha IS A PRIMITIVE ROOT MODULO q
def is_primitive_root(alpha, q):
    if not (1 < alpha < q):
        return False

    for factor in prime_factors(q - 1):
        if pow(alpha, (q - 1) // factor, q) == 1:
            return False

    return True


# 4. CALCULATE PUBLIC KEY
def calculate_public_key(alpha, private_key, q):
    return pow(alpha, private_key, q)


# 5. CALCULATE SHARED SECRET KEY
def calculate_shared_key(received_key, private_key, q):
    return pow(received_key, private_key, q)


# 6. INPUT AND VALIDATE PUBLIC PARAMETERS
def input_public_parameters():
    while True:
        try:
            q = int(input("Enter prime number q: "))

            if not is_prime(q):
                print("Error: q must be a prime number. Try again.")
                continue

            alpha = int(input("Enter primitive root alpha: "))

            if not is_primitive_root(alpha, q):
                print("Error: alpha must be a primitive root modulo q. Try again.")
                continue

            return q, alpha

        except ValueError:
            print("Error: Please enter integers only.")


# 7. INPUT AND VALIDATE PRIVATE KEYS
def input_private_key(name, q):
    while True:
        try:
            private_key = int(input(f"Enter private key of {name}: "))

            if not (1 <= private_key < q - 1):
                print(f"Error: Private key must be between 1 and {q - 2}.")
                continue

            return private_key

        except ValueError:
            print("Error: Please enter an integer.")


# 8. MAIN PROGRAM
def main():
    print("=" * 55)
    print("          DIFFIE-HELLMAN KEY EXCHANGE")
    print("=" * 55)

    # Input public parameters
    print("\n[STEP 1] PUBLIC PARAMETERS")
    q, alpha = input_public_parameters()

    # Input private keys
    print("\n[STEP 2] PRIVATE KEYS")
    xA = input_private_key("A", q)
    xB = input_private_key("B", q)

    # Calculate public keys
    print("\n[STEP 3] GENERATE PUBLIC KEYS")
    yA = calculate_public_key(alpha, xA, q)
    yB = calculate_public_key(alpha, xB, q)

    print("Public key of A:", yA)
    print("Public key of B:", yB)

    # Simulate public key exchange
    print("\n[STEP 4] PUBLIC KEY EXCHANGE")
    public_key_received_by_A = yB
    public_key_received_by_B = yA

    print("A receives public key from B:", public_key_received_by_A)
    print("B receives public key from A:", public_key_received_by_B)

    # Calculate shared secret keys
    print("\n[STEP 5] CALCULATE SHARED SECRET KEYS")
    KA = calculate_shared_key(public_key_received_by_A, xA, q)
    KB = calculate_shared_key(public_key_received_by_B, xB, q)

    print("Shared key calculated by A:", KA)
    print("Shared key calculated by B:", KB)

    # Verify shared keys
    print("\n[STEP 6] VERIFY SHARED KEYS")

    if KA == KB:
        print("SUCCESS: Both parties have the same shared secret key.")
        print("Shared secret key:", KA)
    else:
        print("FAILED: The shared secret keys do not match.")

    # Display summary
    print("\n" + "=" * 55)
    print("                 FINAL RESULTS")
    print("=" * 55)

    print("Prime number (q):", q)
    print("Primitive root (alpha):", alpha)
    print("Private key of A:", xA)
    print("Private key of B:", xB)
    print("Public key of A:", yA)
    print("Public key of B:", yB)
    print("Shared key of A:", KA)
    print("Shared key of B:", KB)

    print("=" * 55)


# 9. RUN PROGRAM
if __name__ == "__main__":
    main()