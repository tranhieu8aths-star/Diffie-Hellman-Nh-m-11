# VERSION 1: BASIC DIFFIE-HELLMAN

q = 353
alpha = 3

xA = 97
xB = 233

yA = pow(alpha, xA, q)
yB = pow(alpha, xB, q)

KA = pow(yB, xA, q)
KB = pow(yA, xB, q)

print("===== DIFFIE-HELLMAN =====")

print("Public parameters:")
print("q =", q)
print("alpha =", alpha)

print("\nPrivate keys:")
print("Private key A =", xA)
print("Private key B =", xB)

print("\nPublic keys:")
print("Public key A =", yA)
print("Public key B =", yB)

print("\nShared keys:")
print("Key A =", KA)
print("Key B =", KB)